package top.wzln.forDemo6;

public class ForDemo1_JumpTenTimes {
    static void main(String[] args) {
        /*
            实现游戏中连续跳跃10次,用输出语句模拟跳跃的逻辑
            格式:
                for(初始化语句;条件判断语句;条件控制语句){
                    循环体语句
                }

                初始化语句:开始条件1
                条件判断语句:结束条件 100
                条件控制语句: +1  i++

                循环体:重复执行的代码
         */

        for(int i = 1;i <= 10;i++){
            System.out.println("游戏人物正在跳跃");
        }

    }
}
